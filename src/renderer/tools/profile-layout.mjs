import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('C:/Users/pc_09/AppData/Local/npm-cache/_npx/e41f203b7505f1fb/node_modules/playwright-core');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://127.0.0.1:5198/?officeDemo=busy', { waitUntil: 'networkidle' });
await page.waitForTimeout(8000);
const cdp = await page.context().newCDPSession(page);
await cdp.send('Performance.enable');
const metrics = async () => Object.fromEntries((await cdp.send('Performance.getMetrics')).metrics.map(m => [m.name, m.value]));
const measure = async name => {
  const a = await metrics();
  await page.waitForTimeout(5000);
  const b = await metrics();
  console.log(name, { busy: +((b.TaskDuration - a.TaskDuration) / 5).toFixed(3), layouts: +((b.LayoutCount - a.LayoutCount) / 5).toFixed(1) });
};
await measure('visible');
await page.evaluate(() => document.querySelector('.office-scene').style.display = 'none');
await measure('hidden');
await browser.close();
